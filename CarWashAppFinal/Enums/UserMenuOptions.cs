namespace CarWashAppFinal.Enums
{
    /// <summary>
    /// Represents the options available in the user menu.
    /// </summary>
    public enum UserMenuOptions
    {
        /// <summary>
        /// Represents the option to add a vehicle.
        /// </summary>
        Add = 1,

        /// <summary>
        /// Represents the option to view all vehicle.
        /// </summary>
        View = 2,

        /// <summary>
        /// Represents the option to start a car wash.
        /// </summary>
        Wash = 3,

        /// <summary>
        /// Represents the option to view wash history.
        /// </summary>
        History = 4,

        /// <summary>
        /// Represents the option to view notifications.
        /// </summary>
        Notification = 5,

        /// <summary>
        /// Represents the option to log out of the application.
        /// </summary>
        Logout = 6,
    }
}
